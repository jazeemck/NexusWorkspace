"use client";
import { useState } from "react";
import toast from "react-hot-toast";
import Button from "@/components/ui/Button";
import { Clipboard, Download, Check } from "lucide-react";

interface ExportBarProps {
  summaryId: string;
  videoTitle: string;
  tldr: string;
  translatedSummary: string;
  timestampSummary: Array<{ timestamp: string; summary: string }>;
  actionItems: string[];
  category?: string;
}

export default function ExportBar({ 
  videoTitle, 
  tldr, 
  translatedSummary, 
  timestampSummary, 
  actionItems,
  category = "General Intelligence"
}: ExportBarProps) {
  const [copied, setCopied] = useState(false);
  const [pdfLoading, setPdfLoading] = useState(false);

  // Map category to display headers
  const categoryHeaders: Record<string, string> = {
    "Lectures & Tutorials": "Structured Learning Notes",
    "News & Interviews": "Key Statements & Quotes",
    "Business Content": "Strategic Business Intelligence",
    "Documentaries": "Analytical Narrative Insights",
    "General Intelligence": "Executive Summary"
  };

  const currentHeader = categoryHeaders[category] || "Executive Summary";

  const buildText = (format: "txt" | "md" = "md") => {
    const divider = format === "md" ? "---" : "--------------------------------------------------";
    const h1 = format === "md" ? "# " : "";
    const h2 = format === "md" ? "## " : "";

    const lines = [
      `${h1}${videoTitle.toUpperCase()}`,
      divider,
      "",
      `${h2}${currentHeader.toUpperCase()}`,
      tldr,
      "",
      `${h2}TRANSLATED ANALYSIS`,
      translatedSummary,
      "",
      `${h2}DEEP ANALYSIS (TIMESTAMPS)`,
      ...timestampSummary.map((k) => `[${k.timestamp}] ${k.summary}`),
      "",
      `${h2}ACTION ITEMS`,
      ...actionItems.map((a, i) => `${i + 1}. ${a}`),
      "",
      divider,
      `Generated by Nexus Workspace • ${new Date().toLocaleString()}`,
    ];
    return lines.join("\n");
  };

  const handleCopy = async () => {
    try {
      await navigator.clipboard.writeText(buildText("md"));
      setCopied(true);
      toast.success("Copied to clipboard!");
      setTimeout(() => setCopied(false), 2000);
    } catch {
      toast.error("Failed to copy. Please try again.");
    }
  };

  const downloadFile = (content: string, extension: string) => {
    try {
      // Add UTF-8 BOM for multilingual support in Windows editors
      const blob = new Blob(["\ufeff" + content], { type: "text/plain;charset=utf-8" });
      const url = URL.createObjectURL(blob);
      const link = document.createElement("a");
      link.href = url;
      link.download = `${videoTitle.slice(0, 40).replace(/[^a-z0-9]/gi, "_")}_intelligence.${extension}`;
      document.body.appendChild(link);
      link.click();
      document.body.removeChild(link);
      URL.revokeObjectURL(url);
      toast.success(`Report downloaded as .${extension}`);
    } catch (err) {
      console.error(err);
      toast.error("Download failed.");
    }
  };

  const handlePdf = async () => {
    // Keep PDF as requested, but warn/handle if it might fail with Unicode
    // For now, let's just make it work as best it can or favor the text download
    setPdfLoading(true);
    try {
      const { default: jsPDF } = await import("jspdf");
      const doc = new jsPDF({ orientation: "portrait", unit: "mm", format: "a4" });

      const margin = 20;
      const pageWidth = doc.internal.pageSize.getWidth();
      const maxWidth = pageWidth - margin * 2;
      let y = margin;

      const addText = (text: string, size: number, bold = false, color: [number, number, number] = [0, 0, 0]) => {
        doc.setFontSize(size);
        doc.setFont("helvetica", bold ? "bold" : "normal");
        doc.setTextColor(...color);
        const lines = doc.splitTextToSize(text, maxWidth);
        if (y + lines.length * (size * 0.4) > 280) { doc.addPage(); y = margin; }
        doc.text(lines, margin, y);
        y += lines.length * (size * 0.4) + 2;
      };

      doc.setFillColor(255, 255, 255);
      doc.rect(0, 0, pageWidth, 297, "F");

      addText("Nexus Report", 22, true, [0, 0, 0]);
      y += 4;
      addText(videoTitle, 14, true, [0, 0, 0]);
      y += 8;

      addText(currentHeader.toUpperCase(), 12, true, [0, 0, 0]);
      y += 1;
      addText(tldr, 10, false, [63, 63, 70]);
      y += 6;

      if (translatedSummary) {
        addText("TRANSLATED ANALYSIS", 12, true, [0, 0, 0]);
        y += 1;
        addText(translatedSummary, 10, false, [63, 63, 70]);
        y += 6;
      }

      addText("DEEP ANALYSIS (TIMESTAMPS)", 12, true, [0, 0, 0]);
      y += 1;
      timestampSummary.forEach((k) => {
        addText(`[${k.timestamp}]`, 9, true, [0, 0, 0]);
        y -= 2;
        addText(k.summary, 9, false, [63, 63, 70]);
        y += 2;
      });
      y += 4;

      addText("ACTION ITEMS", 12, true, [0, 0, 0]);
      y += 1;
      actionItems.forEach((a, i) => addText(`${i + 1}. ${a}`, 9, false, [63, 63, 70]));

      doc.save(`${videoTitle.slice(0, 40).replace(/[^a-z0-9]/gi, "_")}_summary.pdf`);
      toast.success("PDF exported!");
    } catch (err) {
      console.error(err);
      toast.error("PDF generation failed.");
    } finally {
      setPdfLoading(false);
    }
  };

  return (
    <div className="flex items-center gap-3 flex-wrap">
      <Button
        variant="primary"
        size="sm"
        onClick={handleCopy}
        className="gap-2 h-11 px-6 rounded-xl transition-all uppercase tracking-widest text-[10px]"
      >
        {copied ? (
          <Check className="w-4 h-4" />
        ) : (
          <Clipboard className="w-4 h-4 text-muted-foreground transition-colors group-hover:text-background" />
        )}
        {copied ? "Status: Copied" : "Copy Intelligence"}
      </Button>

      <Button
        variant="primary"
        size="sm"
        onClick={() => downloadFile(buildText("txt"), "txt")}
        className="gap-2 h-11 px-6 rounded-xl transition-all uppercase tracking-widest text-[10px]"
      >
        <Download className="w-4 h-4 text-muted-foreground transition-colors group-hover:text-background" />
        Download Text (UTF-8)
      </Button>

      <Button
        variant="primary"
        size="sm"
        onClick={handlePdf}
        loading={pdfLoading}
        className="gap-2 h-11 px-6 rounded-xl transition-all uppercase tracking-widest text-[10px]"
      >
        <Download className="w-4 h-4 text-muted-foreground transition-colors group-hover:text-background" />
        Download PDF
      </Button>
    </div>
  );
}
